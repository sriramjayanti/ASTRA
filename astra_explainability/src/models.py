@dataclass
class ExplainabilityResult:
    """
    Comprehensive output of ASTRA Stage 15 Explainability & Confidence Reasoning Engine.
    Exposes auditable decision rationales, confidence decomposition, candidate comparisons,
    and machine-readable graphs.
    """
    signal_id: str
    best_pipeline_id: str
    overall_status: AstraStatus
    overall_confidence: float
    calibrated_probability: Optional[float] = None

    field_explanations: Dict[str, FieldExplanation] = field(default_factory=dict)
    candidate_comparison: List[CandidateExplanation] = field(default_factory=list)
    evidence_summary: List[EvidenceItem] = field(default_factory=list)
    contradictions: List[Contradiction] = field(default_factory=list)
    missing_evidence: List[MissingEvidence] = field(default_factory=list)
    uncertainty_sources: List[str] = field(default_factory=list)
    alternative_hypotheses: List[Dict[str, Any]] = field(default_factory=list)

    confidence_breakdown: Optional[ConfidenceBreakdown] = None
    reasoning_graph: Optional[ReasoningGraph] = None
    reasoning_trace: List[str] = field(default_factory=list)

    human_summary: str = ""
    technical_summary: str = ""
    gui_summary: Optional[GuiSummary] = None

    model_versions: Dict[str, str] = field(default_factory=dict)
    processing_versions: Dict[str, str] = field(default_factory=dict)
    processing_provenance: Dict[str, Any] = field(default_factory=dict)
    warnings: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "signal_id": self.signal_id,
            "best_pipeline_id": self.best_pipeline_id,
            "overall_status": self.overall_status.value,
            "overall_confidence": round(float(self.overall_confidence), 4),
            "calibrated_probability": round(float(self.calibrated_probability), 4) if self.calibrated_probability is not None else None,
            "fields": {k: v.to_dict() for k, v in self.field_explanations.items()},
            "confidence_breakdown": self.confidence_breakdown.to_dict() if self.confidence_breakdown else None,
            "candidate_comparison": [c.to_dict() for c in self.candidate_comparison],
            "evidence_summary_count": len(self.evidence_summary),
            "contradictions": [c.to_dict() for c in self.contradictions],
            "missing_evidence": [m.to_dict() for m in self.missing_evidence],
            "uncertainty_sources": self.uncertainty_sources,
            "alternative_hypotheses": self.alternative_hypotheses,
            "reasoning_graph": self.reasoning_graph.to_dict() if self.reasoning_graph else None,
            "reasoning_trace": self.reasoning_trace,
            "human_summary": self.human_summary,
            "technical_summary": self.technical_summary,
            "gui_summary": self.gui_summary.to_dict() if self.gui_summary else None,
            "model_versions": self.model_versions,
            "processing_versions": self.processing_versions,
            "warnings": self.warnings
        }
