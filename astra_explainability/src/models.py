class CandidateExplanation:
    """Comparative analysis for an individual candidate pipeline."""
    pipeline_id: str
    rank: int
    score: float
    status: AstraStatus
    margin_to_next: float
    key_strengths: List[str]
    key_weaknesses: List[str]
    why_lost: Optional[str]
    field_values: Dict[str, Any]

    def __init__(
        self,
        pipeline_id: str,
        rank: int = 1,
        score: float = 0.0,
        status: Any = AstraStatus.CONFIRMED,
        margin_to_next: Any = 0.0,
        key_strengths: Any = None,
        key_weaknesses: Any = None,
        why_lost: Any = None,
        field_values: Any = None,
        **kwargs
    ):
        self.pipeline_id = str(pipeline_id)
        self.rank = int(rank)
        self.score = float(score)

        # Handle legacy positional calls: (pipeline_id, rank, score, val_score, mod, baud, intl, fec, is_best)
        if isinstance(margin_to_next, str) or isinstance(status, (int, float)):
            # Legacy signature
            st_val = AstraStatus.CONFIRMED if self.score >= 0.85 else AstraStatus.ESTIMATED
            self.status = st_val
            self.margin_to_next = 0.35
            self.key_strengths = []
            self.key_weaknesses = []
            self.why_lost = None
            self.field_values = {
                "modulation": str(margin_to_next),
                "symbol_rate": float(key_strengths) if isinstance(key_strengths, (int, float)) else key_strengths,
                "interleaver": key_weaknesses,
                "fec": why_lost
            }
        else:
            if isinstance(status, str):
                try:
                    self.status = AstraStatus(status)
                except ValueError:
                    self.status = AstraStatus.CONFIRMED
            else:
                self.status = status or AstraStatus.CONFIRMED
            self.margin_to_next = float(margin_to_next) if margin_to_next is not None else 0.0
            self.key_strengths = list(key_strengths) if isinstance(key_strengths, (list, tuple)) else []
            self.key_weaknesses = list(key_weaknesses) if isinstance(key_weaknesses, (list, tuple)) else []
            self.why_lost = str(why_lost) if why_lost is not None else None
            self.field_values = dict(field_values) if isinstance(field_values, dict) else {}

    @property
    def is_best(self) -> bool:
        return self.rank in (0, 1)

    @property
    def modulation(self) -> Any:
        return self.field_values.get("modulation")

    @property
    def symbol_rate(self) -> Any:
        return self.field_values.get("symbol_rate")

    @property
    def fec_scheme(self) -> Any:
        return self.field_values.get("fec") or self.field_values.get("fec_scheme")

    @property
    def interleaver(self) -> Any:
        return self.field_values.get("interleaver")

    def to_dict(self) -> Dict[str, Any]:
        return {
            "pipeline_id": self.pipeline_id,
            "rank": self.rank,
            "score": round(float(self.score), 4),
            "status": self.status.value,
            "margin_to_next": round(float(self.margin_to_next), 4),
            "key_strengths": self.key_strengths,
            "key_weaknesses": self.key_weaknesses,
            "why_lost": self.why_lost,
            "field_values": self.field_values
        }


@dataclass
class ConfidenceBreakdown:
    """Component-by-component decomposition of final confidence."""
    overall_score: float = 0.0
    calibrated_probability: Optional[float] = None
    modulation_confidence: float = 0.0
    symbol_rate_confidence: float = 0.0
    synchronization_confidence: float = 0.0
    demodulation_confidence: float = 0.0
    interleaver_confidence: float = 0.0
    fec_confidence: float = 0.0
    validation_confidence: float = 0.0
    structure_confidence: float = 0.0
    payload_confidence: float = 0.0
    contradiction_penalty: float = 0.0
    margin_adjustment: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "overall_score": round(float(self.overall_score), 4),
            "calibrated_probability": round(float(self.calibrated_probability), 4) if self.calibrated_probability is not None else None,
            "components": {
                "modulation": round(float(self.modulation_confidence), 4),
                "symbol_rate": round(float(self.symbol_rate_confidence), 4),
                "synchronization": round(float(self.synchronization_confidence), 4),
                "demodulation": round(float(self.demodulation_confidence), 4),
                "interleaver": round(float(self.interleaver_confidence), 4),
                "fec": round(float(self.fec_confidence), 4),
                "validation": round(float(self.validation_confidence), 4),
                "structure": round(float(self.structure_confidence), 4),
                "payload": round(float(self.payload_confidence), 4),
            },
            "penalties_and_adjustments": {
                "contradiction_penalty": round(float(self.contradiction_penalty), 4),
                "margin_adjustment": round(float(self.margin_adjustment), 4)
            }
        }


@dataclass
class ReasoningNode:
    """Graph node representing an individual claim, stage, or evidence item."""
    node_id: str
    node_type: NodeType
    label: str
    details: str = ""
    stage: str = ""
    status: Optional[AstraStatus] = None
    confidence_score: Optional[float] = None
    properties: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "node_id": self.node_id,
            "node_type": self.node_type.value,
            "label": self.label,
            "details": self.details,
            "stage": self.stage,
            "status": self.status.value if self.status else None,
            "confidence_score": round(float(self.confidence_score), 4) if self.confidence_score is not None else None,
            "properties": self.properties
        }


@dataclass
class ReasoningEdge:
    """Directed edge linking reasoning nodes in the explanation graph."""
    source_id: str
    target_id: str
    edge_type: EdgeType
    weight: float = 1.0
    description: str = ""
    label: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "source_id": self.source_id,
            "target_id": self.target_id,
            "edge_type": self.edge_type.value,
            "weight": round(float(self.weight), 4),
            "description": self.description or self.label,
            "label": self.label or self.description
        }


@dataclass
class ReasoningGraph:
    """Machine-readable directed graph of evidence, stages, and claims."""
    nodes: List[ReasoningNode] = field(default_factory=list)
    edges: List[ReasoningEdge] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "node_count": len(self.nodes),
            "edge_count": len(self.edges),
            "nodes": [n.to_dict() for n in self.nodes],
            "edges": [e.to_dict() for e in self.edges]
        }


@dataclass
class GuiCard:
    """Compact summary card tailored for GUI badges and dashboard views."""
    field_name: str
    value_str: str = ""
    status: AstraStatus = AstraStatus.UNKNOWN
    confidence_pct: int = 0
    badge_color: str = "gray"  # green, cyan, amber, gray
    title: str = ""
    value_display: str = ""
    confidence_display: str = ""
    subtitle: str = ""

    def __post_init__(self):
        if not self.value_str and self.value_display:
            self.value_str = self.value_display
        if not self.value_display and self.value_str:
            self.value_display = self.value_str
        if not self.title:
            self.title = self.field_name.replace("_", " ").title()
        if not self.confidence_display and self.confidence_pct:
            self.confidence_display = f"{self.confidence_pct}%"

    @property
    def primary_value(self) -> str:
        return self.value_display or self.value_str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "field_name": self.field_name,
            "title": self.title,
            "value_display": self.value_display or self.value_str,
            "status": self.status.value,
            "confidence_display": self.confidence_display,
            "confidence_pct": self.confidence_pct,
            "badge_color": self.badge_color,
            "subtitle": self.subtitle
        }


